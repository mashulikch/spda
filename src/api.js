//
// Что умеет сервер:
//   GET    API_URL + '/api/memes'               → массив мемов { id, title, image, likes, liked }
//   POST   API_URL + '/api/memes/' + id + '/like' → поставить лайк, в ответе мем с новыми likes и liked
//   DELETE на тот же адрес                         → снять лайк
//
// 1. Опции запроса передаются вторым аргументом: fetch(адрес, { … }).
//    Для нашего сервера там всегда нужна credentials: 'include'. Сервер живёт на другом сайте,
//    и без этой опции браузер не отправит и не сохранит cookie с вашим токеном: лента загрузится,
//    но сервер не вспомнит ваши лайки, а лайк получит ответ 401.
//    Для лайка там же указывается метод: method: 'POST' или 'DELETE'.
// 2. fetch не считает 404 и 500 ошибкой. Проверяйте res.ok и бросайте ошибку сами, если он false.
// 3. Сбой сети и брошенную вами ошибку ловит .catch(…) в конце цепочки — там переключайтесь на экран ошибки.
//    Кнопка «Повторить» просто запускает загрузку ещё раз: вынесите её в отдельную функцию.
// 4. Сколько состояний у экрана ленты: загрузка, ошибка, пусто (пришёл []), данные. Удобно хранить одно
//    состояние-статус вместо нескольких флагов.
